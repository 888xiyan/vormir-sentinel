from __future__ import annotations

import unittest

from vormir_sentinel.relics import RelicError, RelicGenerator, resolve_output_root
from vormir_sentinel.state import ProgressState


class RelicTests(unittest.TestCase):
    def test_generate_creates_only_harmless_known_artifacts(self) -> None:
        generator = RelicGenerator("vormir-output-test")
        state = ProgressState(cleared=True, tribute_count=5)

        try:
            generated = generator.generate(state)

            paths = {item.path.name for item in generated}
            self.assertTrue(
                {
                    "A_DEED_OF_SACRIFICE.txt",
                    "polyglot_relic.txt",
                    "polyglot_relic.bf",
                    "whitespace_relic.ws",
                    "resurrection.html",
                }.issubset(paths)
            )
            self.assertTrue(state.relic_generated)
            deed = (generator.output_root / "A_DEED_OF_SACRIFICE.txt").read_text()
            self.assertIn("No host file", deed)
            resurrection = (generator.output_root / "resurrection.html").read_text()
            self.assertIn("github.com/888xiyan/vormir-sentinel", resurrection)
        finally:
            generator.clean()

    def test_clean_preserves_unrelated_files(self) -> None:
        generator = RelicGenerator("vormir-output-test")
        generator.output_root.mkdir(parents=True, exist_ok=True)
        unrelated = generator.output_root / "keep-me.txt"
        unrelated.write_text("not generated by Vormir", encoding="utf-8")

        try:
            removed = generator.clean()

            self.assertFalse(removed)
            self.assertTrue(unrelated.exists())
        finally:
            unrelated.unlink(missing_ok=True)
            if generator.output_root.exists():
                generator.output_root.rmdir()

    def test_absolute_or_escaping_output_paths_are_rejected(self) -> None:
        with self.assertRaises(RelicError):
            resolve_output_root("/tmp/vormir-output")
        with self.assertRaises(RelicError):
            resolve_output_root("../vormir-output")
        with self.assertRaises(RelicError):
            resolve_output_root(".")


if __name__ == "__main__":
    unittest.main()
